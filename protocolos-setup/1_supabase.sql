-- 1) Protocolos em aberto na última extração (uma linha por protocolo)
create table if not exists public.protocolos (
  id               bigint generated by default as identity primary key,
  data_extracao    date,
  numero_protocolo text,
  status           text,
  criado_em        timestamp,
  agente           text,
  setor            text,
  categoria        text
);

-- 2) Saldo por setor em cada extração (espelho da aba SALDO PROTOCOLOS)
create table if not exists public.protocolos_saldo (
  id                         bigint generated by default as identity primary key,
  data_extracao              date,
  tipo                       text,
  setor                      text,
  saldo_anterior             integer,
  novos                      integer,
  transferidos_entrada       integer,
  transferidos_saida         integer,
  fechados                   integer,
  saldo_atual                integer,
  pendentes_mais_30_dias     integer,
  tempo_medio_em_aberto_dias numeric,
  taxa_fechamento            numeric
);

-- 3) Movimento entre extrações (espelho da aba MOVIMENTO PROTOCOLOS)
create table if not exists public.protocolos_movimento (
  id               bigint generated by default as identity primary key,
  data_extracao    date,
  numero_protocolo text,
  movimento        text,
  setor            text,
  setor_anterior   text,
  agente           text,
  categoria        text,
  criado_em        timestamp,
  dias_em_aberto   integer
);

create index if not exists protocolos_setor_idx           on public.protocolos (setor);
create index if not exists protocolos_saldo_setor_idx     on public.protocolos_saldo (setor);
create index if not exists protocolos_movimento_setor_idx on public.protocolos_movimento (setor);

-- Mesma regra de acesso das outras tabelas do painel:
-- administrador vê tudo; os demais veem só o próprio setor. Ninguém altera pelo painel.
alter table public.protocolos           enable row level security;
alter table public.protocolos_saldo     enable row level security;
alter table public.protocolos_movimento enable row level security;

drop policy if exists "Ver apenas o próprio setor" on public.protocolos;
create policy "Ver apenas o próprio setor" on public.protocolos
  for select using (is_admin() or (setor = meu_setor()));

drop policy if exists "Ver apenas o próprio setor" on public.protocolos_saldo;
create policy "Ver apenas o próprio setor" on public.protocolos_saldo
  for select using (is_admin() or (setor = meu_setor()));

drop policy if exists "Ver apenas o próprio setor" on public.protocolos_movimento;
create policy "Ver apenas o próprio setor" on public.protocolos_movimento
  for select using (is_admin() or (setor = meu_setor()));

grant select on public.protocolos, public.protocolos_saldo, public.protocolos_movimento to authenticated;
