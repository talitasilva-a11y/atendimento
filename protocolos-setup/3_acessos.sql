-- ============================================================
-- RELATÓRIO DE ACESSOS — registra cada entrada no painel
-- Rodar UMA vez no Supabase: SQL Editor > New query > colar > Run.
-- Pode rodar de novo sem problema (não apaga dados).
-- Usa as funções is_admin() que o painel já tem.
-- ============================================================

create table if not exists public.acessos_log (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null default auth.uid(),
  email        text,
  nome         text,
  setor        text,
  tipo         text,          -- 'login' (digitou a senha) ou 'sessao' (reabriu o site já logado)
  navegador    text,
  acessado_em  timestamptz not null default now()
);
create index if not exists acessos_log_data_idx on public.acessos_log (acessado_em desc);
create index if not exists acessos_log_user_idx on public.acessos_log (user_id);

-- Preenche e-mail, nome e setor a partir do cadastro (o navegador não consegue falsificar).
create or replace function public.acessos_log_preencher()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  new.user_id     := auth.uid();
  new.acessado_em := now();
  new.email       := (select email from auth.users where id = auth.uid());
  select p.nome, case when p.is_admin then 'Admin' else p.setor end
    into new.nome, new.setor
    from public.perfis p where p.id = auth.uid();
  if new.tipo not in ('login','sessao') then new.tipo := 'sessao'; end if;
  return new;
end $$;

drop trigger if exists acessos_log_preencher on public.acessos_log;
create trigger acessos_log_preencher before insert on public.acessos_log
  for each row execute function public.acessos_log_preencher();

alter table public.acessos_log enable row level security;

-- Qualquer usuário logado só consegue registrar o PRÓPRIO acesso.
drop policy if exists "Registrar o próprio acesso" on public.acessos_log;
create policy "Registrar o próprio acesso" on public.acessos_log
  for insert to authenticated with check (user_id = auth.uid());

-- Só o administrador lê o relatório. Ninguém edita nem apaga pelo painel.
drop policy if exists "Admin vê os acessos" on public.acessos_log;
create policy "Admin vê os acessos" on public.acessos_log
  for select to authenticated using (is_admin());

grant insert, select on public.acessos_log to authenticated;
